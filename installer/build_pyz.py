#!/usr/bin/env python3
"""Build a single-file Edward installer (Python zipapp).

Usage:
    python3 installer/build_pyz.py
    ./dist/edward-installer.pyz --target /path/to/project

Resources are read from the project root (agents/, bin/, scripts/, templates/,
ui.json) and installed into the target project's .opencode/ directory. It never
creates edward/ artifacts; run `.opencode/bin/edward init` afterwards.
"""

from __future__ import annotations

import shutil
import sys
import tempfile
import zipapp
from pathlib import Path

from release import read_release_version, write_version_file


INSTALLER_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = INSTALLER_DIR.parent
RESOURCE_ROOT = PROJECT_ROOT
DIST_DIR = PROJECT_ROOT / "dist"
INSTALLER = DIST_DIR / "edward-installer.pyz"
PAYLOAD_IGNORE = shutil.ignore_patterns(".DS_Store", "__pycache__", "*.pyc", "*.pyo")

INSTALLER_MAIN = r'''#!/usr/bin/env python3
"""Edward resource installer (generated by installer/build_pyz.py)."""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

VERSION = "__VERSION__"


def copy_payload(payload: Path, target: Path, force: bool) -> None:
    opencode_target = target / ".opencode"
    agent_file = opencode_target / "agents" / "edward.md"
    if agent_file.exists() and not force:
        raise SystemExit(
            f"{agent_file} 已存在。使用 --force 覆盖资源（不会删除 edward/ 工件）。"
        )

    for source in sorted(payload.rglob("*")):
        if not source.is_file():
            continue
        relative = source.relative_to(payload)
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists() and not force:
            continue
        shutil.copy2(source, destination)


def make_executable(target: Path) -> None:
    for relative in (".opencode/bin/edward", ".opencode/scripts/edward.py"):
        path = target / relative
        if path.exists():
            path.chmod(0o755)


def main() -> int:
    parser = argparse.ArgumentParser(prog="edward-installer")
    parser.add_argument("--version", action="version", version="Edward Installer " + VERSION)
    parser.add_argument("--target", default=".", help="目标项目目录，默认当前目录")
    parser.add_argument("--force", action="store_true", help="覆盖已安装的资源")
    parser.add_argument("--init", action="store_true", help="安装后立即创建 edward/ 工件目录")
    args = parser.parse_args()

    target = Path(args.target).expanduser().resolve()
    if not target.exists():
        raise SystemExit(f"目标目录不存在: {target}")

    archive = Path(sys.argv[0]).resolve()
    with tempfile.TemporaryDirectory(prefix="edward-payload-") as tmp:
        if zipfile.is_zipfile(archive):
            with zipfile.ZipFile(archive) as zf:
                zf.extractall(tmp)
            payload = Path(tmp) / "payload"
        else:
            payload = Path(__file__).resolve().parent / "payload"
        copy_payload(payload, target, args.force)
    make_executable(target)

    print(f"Edward {VERSION} 资源已安装到: {target / '.opencode'}")

    edward_bin = target / ".opencode" / "bin" / "edward"
    if args.init:
        subprocess.run([str(edward_bin), "init"], cwd=target, check=True)
    else:
        print("下一步: .opencode/bin/edward init")
    print("启动: .opencode/bin/edward serve --daemon")
    print("状态: .opencode/bin/edward status")
    print("UI:   http://127.0.0.1:8765/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def build() -> Path:
    version = read_release_version()
    with tempfile.TemporaryDirectory(prefix="edward-installer-") as tmp:
        staging = Path(tmp)
        payload = staging / "payload"
        resources = [
            (RESOURCE_ROOT / "ui.json", payload / ".opencode" / "ui.json"),
            (RESOURCE_ROOT / "agents", payload / ".opencode" / "agents"),
            (RESOURCE_ROOT / "bin", payload / ".opencode" / "bin"),
            (RESOURCE_ROOT / "templates", payload / ".opencode" / "templates"),
            (RESOURCE_ROOT / "scripts" / "edward.py", payload / ".opencode" / "scripts" / "edward.py"),
        ]
        for source, destination in resources:
            if source.is_dir():
                shutil.copytree(source, destination, ignore=PAYLOAD_IGNORE)
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, destination)

        write_version_file(payload / ".opencode" / "VERSION", version)

        (staging / "__main__.py").write_text(
            INSTALLER_MAIN.replace("__VERSION__", version),
            encoding="utf-8",
        )
        DIST_DIR.mkdir(parents=True, exist_ok=True)
        if INSTALLER.exists():
            INSTALLER.unlink()
        zipapp.create_archive(
            staging,
            target=INSTALLER,
            interpreter="/usr/bin/env python3",
            compressed=True,
        )
    INSTALLER.chmod(0o755)
    return INSTALLER


if __name__ == "__main__":
    path = build()
    print(f"已生成: {path}")
    print(f"试运行: {path} --help")
